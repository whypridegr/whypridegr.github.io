// Message keyed to how many the user marked as "δεδομένο" (taken for granted).
export function privilegeMessage(count: number, total: number): string {
  const ratio = count / total;
  if (count === 0)
    return "Δεν τσέκαρες κανένα. Ίσως κουβαλάς ένα φορτίο που οι άλλοι δεν χρειάζεται καν να σκεφτούν.";
  if (ratio < 0.5)
    return "Κάποια τα θεωρείς δεδομένα, κάποια όχι. Αυτή η μέση είναι που οι περισσότεροι δεν τη βλέπουν.";
  if (ratio < 1)
    return "Τα περισσότερα σού φαίνονται αυτονόητα. Για άλλους, καθένα από αυτά είναι μια καθημερινή απόφαση.";
  return "Τα τσέκαρες όλα. Τίποτα από αυτά δεν σου κόστισε ποτέ σκέψη. Αυτό ακριβώς είναι το προνόμιο που δεν φαίνεται.";
}
